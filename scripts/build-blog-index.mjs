#!/usr/bin/env node
/**
 * Inlines every data/*.mdx file into a TypeScript module.
 *
 * The blog used to read its posts off disk at request time. That works under
 * `next start`, but Cloudflare Workers has no filesystem, so any route that
 * missed the prerender cache blew up with ENOENT. Bundling the content at build
 * time removes the runtime dependency entirely and keeps the site portable
 * across runtimes.
 *
 * Runs from `prebuild` / `predev`. The output is generated, not committed.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const DATA_DIR = path.join(ROOT, "data");
const OUT_FILE = path.join(ROOT, "util", "blog-index.generated.ts");

const files = (await fs.readdir(DATA_DIR))
  .filter((f) => f.toLowerCase().endsWith(".mdx"))
  .sort();

const entries = await Promise.all(
  files.map(async (file) => {
    const slug = file.replace(/\.mdx?$/i, "");
    const raw = await fs.readFile(path.join(DATA_DIR, file), "utf-8");
    return `  ${JSON.stringify(slug)}: ${JSON.stringify(raw)},`;
  })
);

const out = `// AUTO-GENERATED by scripts/build-blog-index.mjs — do not edit.
// Regenerate with \`npm run blog:index\` (also runs on predev/prebuild).

/** Raw .mdx source for every post, keyed by slug. */
export const RAW_POSTS: Record<string, string> = {
${entries.join("\n")}
};
`;

await fs.mkdir(path.dirname(OUT_FILE), { recursive: true });
await fs.writeFile(OUT_FILE, out, "utf-8");

console.log(
  `blog index: ${files.length} post${files.length === 1 ? "" : "s"} -> ${path.relative(ROOT, OUT_FILE)}`
);
